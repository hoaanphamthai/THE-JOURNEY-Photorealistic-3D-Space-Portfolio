/**
 * Asset loading with real progress. Textures are WebP by default; if a .ktx2
 * sibling exists (see README → KTX2) it is used instead. Lazy per-body loading:
 * each scene requests its own textures when the camera approaches.
 */
import { TextureLoader, Texture, SRGBColorSpace, LinearFilter, LinearMipmapLinearFilter, type WebGLRenderer } from 'three';
import { KTX2Loader } from 'three/examples/jsm/loaders/KTX2Loader.js';
import { GLTFLoader, type GLTF } from 'three/examples/jsm/loaders/GLTFLoader.js';
import { DRACOLoader } from 'three/examples/jsm/loaders/DRACOLoader.js';

export class Assets {
  private tex = new TextureLoader();
  private ktx2: KTX2Loader;
  private gltf: GLTFLoader;
  private cache = new Map<string, Promise<Texture>>();
  private ktx2Index: Set<string> | null = null;
  maxAniso = 1;

  constructor(renderer: WebGLRenderer) {
    this.ktx2 = new KTX2Loader().setTranscoderPath('/basis/').detectSupport(renderer);
    const draco = new DRACOLoader().setDecoderPath('/draco/');
    this.gltf = new GLTFLoader().setDRACOLoader(draco).setKTX2Loader(this.ktx2);
    this.maxAniso = Math.min(8, renderer.capabilities.getMaxAnisotropy());
  }

  /** /assets/ktx2.json lists which textures have a KTX2 version (generated by scripts/to_ktx2.sh). */
  private async ktx2Available(url: string) {
    if (!this.ktx2Index) {
      this.ktx2Index = await fetch('/assets/ktx2.json')
        .then((r) => (r.ok ? r.json() : []))
        .then((l: string[]) => new Set(l))
        .catch(() => new Set<string>());
    }
    return this.ktx2Index.has(url);
  }

  texture(url: string, { srgb = true, onProgress }: { srgb?: boolean; onProgress?: (p: number) => void } = {}) {
    const hit = this.cache.get(url);
    if (hit) return hit;
    const p = (async () => {
      let t: Texture;
      if (await this.ktx2Available(url)) {
        t = await this.ktx2.loadAsync(url.replace(/\.(webp|png|jpg)$/, '.ktx2'), (e) => onProgress?.(e.loaded / (e.total || 1)));
      } else {
        t = await this.tex.loadAsync(url, (e) => onProgress?.(e.loaded / (e.total || 1)));
        t.generateMipmaps = true;
        t.minFilter = LinearMipmapLinearFilter;
        t.magFilter = LinearFilter;
      }
      t.colorSpace = srgb ? SRGBColorSpace : '';
      t.anisotropy = this.maxAniso;
      t.needsUpdate = true;
      onProgress?.(1);
      return t;
    })();
    this.cache.set(url, p);
    return p;
  }

  model(url: string, onProgress?: (p: number) => void): Promise<GLTF> {
    return this.gltf.loadAsync(url, (e) => onProgress?.(e.loaded / (e.total || 1)));
  }

  async binary(url: string, onProgress?: (p: number) => void): Promise<ArrayBuffer> {
    const res = await fetch(url);
    if (!res.ok || !res.body) throw new Error(`${url}: ${res.status}`);
    const total = Number(res.headers.get('content-length')) || 0;
    const reader = res.body.getReader();
    const chunks: Uint8Array[] = [];
    let got = 0;
    for (;;) {
      const { done, value } = await reader.read();
      if (done) break;
      chunks.push(value);
      got += value.length;
      if (total) onProgress?.(got / total);
    }
    const out = new Uint8Array(got);
    let o = 0;
    for (const c of chunks) {
      out.set(c, o);
      o += c.length;
    }
    onProgress?.(1);
    return out.buffer;
  }

  dispose() {
    this.cache.forEach((p) => p.then((t) => t.dispose()));
    this.cache.clear();
    this.ktx2.dispose();
  }
}

/** Aggregates weighted sub-progress values into one 0..1 number. */
export class Progress {
  private parts = new Map<string, { w: number; p: number }>();
  constructor(private onUpdate: (p: number, label: string) => void) {}
  track(name: string, weight: number) {
    this.parts.set(name, { w: weight, p: 0 });
    return (p: number) => {
      this.parts.get(name)!.p = Math.min(1, p);
      this.emit(name);
    };
  }
  private emit(label: string) {
    let w = 0, acc = 0;
    this.parts.forEach((v) => ((w += v.w), (acc += v.w * v.p)));
    this.onUpdate(w ? acc / w : 0, label);
  }
}
